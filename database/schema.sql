CREATE TABLE IF NOT EXISTS textbook (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  title VARCHAR(100) NOT NULL,
  course_name VARCHAR(100) NOT NULL,
  total_pages INT NOT NULL DEFAULT 0,
  status VARCHAR(30) NOT NULL DEFAULT 'not_prepared',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS lesson (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  textbook_id BIGINT NOT NULL,
  lesson_order INT NOT NULL,
  title VARCHAR(100) NOT NULL,
  objective TEXT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'locked',
  textbook_pages VARCHAR(50) NULL,
  max_duration_minutes INT NOT NULL DEFAULT 40,
  estimated_duration_minutes INT NULL,
  summary TEXT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_lesson_textbook FOREIGN KEY (textbook_id) REFERENCES textbook (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS lesson_script (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  lesson_id BIGINT NOT NULL,
  script_order INT NOT NULL,
  role VARCHAR(30) NOT NULL,
  speaker VARCHAR(50) NOT NULL,
  content TEXT NOT NULL,
  message_type VARCHAR(50) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_lesson_script_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS lesson_node_mapping (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  lesson_id BIGINT NOT NULL,
  node_id BIGINT NOT NULL,
  role VARCHAR(30) NOT NULL,
  display_order INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_lnm_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE,
  CONSTRAINT fk_lnm_node FOREIGN KEY (node_id) REFERENCES kg_node (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS graph_progress (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  node_id BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'locked',
  completed_lesson_id BIGINT NULL,
  completed_at TIMESTAMP NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_gp_node FOREIGN KEY (node_id) REFERENCES kg_node (id) ON DELETE CASCADE,
  CONSTRAINT fk_gp_lesson FOREIGN KEY (completed_lesson_id) REFERENCES lesson (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS lesson_session (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  lesson_id BIGINT NOT NULL,
  started_at TIMESTAMP NULL,
  ended_at TIMESTAMP NULL,
  duration_seconds INT NOT NULL DEFAULT 0,
  status VARCHAR(30) NOT NULL DEFAULT 'in_progress',
  end_type VARCHAR(30) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_ls_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

